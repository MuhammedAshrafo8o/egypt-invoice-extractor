-- دفتر — PostgreSQL schema (Supabase). Same tables as the SQLite schema in app/db.py.
-- Dates are ISO text, like in SQLite, so the queries are shared.

CREATE TABLE IF NOT EXISTS accountants (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    kind          TEXT NOT NULL DEFAULT 'office',
    created_at    TEXT NOT NULL
);
ALTER TABLE accountants ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'office';

CREATE TABLE IF NOT EXISTS clients (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accountant_id     BIGINT NOT NULL REFERENCES accountants(id) ON DELETE CASCADE,
    name              TEXT NOT NULL,
    tax_id            TEXT,
    whatsapp_phone    TEXT UNIQUE,
    eta_client_id     TEXT,
    eta_client_secret TEXT,
    eta_profile       TEXT,
    notes             TEXT,
    created_at        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS invoices (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id         BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    direction         TEXT NOT NULL DEFAULT 'purchase',
    status            TEXT NOT NULL,
    approved          INTEGER NOT NULL DEFAULT 0,
    source_type       TEXT,
    channel           TEXT NOT NULL DEFAULT 'upload',
    original_filename TEXT,
    stored_path       TEXT,
    period            TEXT NOT NULL,
    supplier_name     TEXT,
    supplier_tax_id   TEXT,
    buyer_name        TEXT,
    buyer_tax_id      TEXT,
    invoice_number    TEXT,
    invoice_date      TEXT,
    currency          TEXT DEFAULT 'EGP',
    subtotal          DOUBLE PRECISION,
    vat_rate          DOUBLE PRECISION,
    vat_amount        DOUBLE PRECISION,
    total             DOUBLE PRECISION,
    eta_uuid          TEXT,
    eta_url           TEXT,
    eta_draft         TEXT,
    eta_state         TEXT,
    eta_message       TEXT,
    eta_long_id       TEXT,
    eta_check         TEXT,
    file_hash         TEXT,
    issues_json       TEXT NOT NULL DEFAULT '[]',
    raw_text          TEXT,
    created_at        TEXT NOT NULL,
    updated_at        TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_invoices_client_period ON invoices(client_id, period);
CREATE INDEX IF NOT EXISTS idx_invoices_uuid ON invoices(eta_uuid);
CREATE INDEX IF NOT EXISTS idx_invoices_hash ON invoices(client_id, file_hash);

CREATE TABLE IF NOT EXISTS parties (
    accountant_id BIGINT NOT NULL REFERENCES accountants(id) ON DELETE CASCADE,
    tax_id        TEXT NOT NULL,
    name          TEXT,
    invoice_count INTEGER NOT NULL DEFAULT 0,
    details_json  TEXT,
    last_seen     TEXT NOT NULL,
    PRIMARY KEY (accountant_id, tax_id)
);

CREATE TABLE IF NOT EXISTS upload_jobs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    batch         TEXT NOT NULL,
    filename      TEXT NOT NULL,
    stored_path   TEXT NOT NULL,
    file_hash     TEXT,
    channel       TEXT NOT NULL DEFAULT 'upload',
    state         TEXT NOT NULL DEFAULT 'queued',
    invoice_id    BIGINT,
    message       TEXT,
    reply_to      TEXT,
    message_id    TEXT,
    split         INTEGER NOT NULL DEFAULT 0,
    created_at    TEXT NOT NULL,
    finished_at   TEXT
);
CREATE INDEX IF NOT EXISTS idx_jobs_state ON upload_jobs(state, id);

CREATE TABLE IF NOT EXISTS whatsapp_messages (
    message_id  TEXT PRIMARY KEY,
    phone       TEXT NOT NULL,
    invoice_id  BIGINT,
    created_at  TEXT NOT NULL
);

-- Uploaded invoice files (PDF / photos) when there is no disk to keep them on (serverless).
CREATE TABLE IF NOT EXISTS stored_files (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT REFERENCES clients(id) ON DELETE CASCADE,
    filename    TEXT NOT NULL,
    content     BYTEA NOT NULL,
    size        INTEGER NOT NULL,
    created_at  TEXT NOT NULL
);

-- One background runner at a time (serverless: a lease, not a lock, so it works through the pooler).
CREATE TABLE IF NOT EXISTS job_runner (
    id     INTEGER PRIMARY KEY,
    until  TEXT NOT NULL
);
INSERT INTO job_runner(id, until) VALUES (1, '2000-01-01T00:00:00') ON CONFLICT (id) DO NOTHING;

-- Arabic-insensitive matching used by search (same rules as app.db._norm / normalize_text).
CREATE OR REPLACE FUNCTION norm(value TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT CASE WHEN value IS NULL THEN '' ELSE
    replace(replace(lower(
      regexp_replace(
        replace(replace(
          translate(value, 'إأآىة٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹٫٬،', 'ااايه01234567890123456789.,,'),
        chr(8207), ''), chr(8206), ''),
      '[' || chr(1552) || '-' || chr(1562) || chr(1611) || '-' || chr(1631) || chr(1648) || chr(1600) || ']', '', 'g')
    ), '-', ''), ' ', '')
  END
$$;
